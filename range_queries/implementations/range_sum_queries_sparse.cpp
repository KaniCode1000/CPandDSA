    for (int j = 0; j + (1 << i) <= N; j++)
        st[i][j] = st[i - 1][j] + st[i - 1][j + (1 << (i - 1))];

//for a query - iterating over all powers of i from K = log(n) to 0 until we reach a power such that 2^i <= R-L+1 (the remaining length left to compute)
